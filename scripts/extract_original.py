#!/usr/bin/env python3
"""
One-time extraction of the original single-file landing page.

Usage:  python3 scripts/extract_original.py "../landing-page-mil-wa (2).html"

Produces:
  public/fonts/*.otf              – SF Pro Display (was Base64 in @font-face)
  public/assets/*                 – images + testimonial videos (were Base64)
  src/site/generated/styles.ts    – every <style> block, verbatim, font URLs rewritten
  src/site/generated/icons.ts     – icon registry built from the original inline SVGs
  src/site/generated/assets.ts    – intrinsic sizes of the extracted images
  scripts/.original-body.html     – normalised original <body>, used by the fidelity check
"""
import base64, hashlib, json, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = sys.argv[1]
html = open(SRC, encoding="utf-8").read()

os.makedirs(f"{ROOT}/public/fonts", exist_ok=True)
os.makedirs(f"{ROOT}/public/assets", exist_ok=True)
os.makedirs(f"{ROOT}/src/site/generated", exist_ok=True)

# Order of data: URIs in the document (verified during the audit).
NAMES = [
    "fonts/sf-pro-display-400.otf", "fonts/sf-pro-display-500.otf", "fonts/sf-pro-display-700.otf",
    "assets/hero-bg.jpg", "assets/logo-mil.png",
    "assets/clients-desktop.png", "assets/clients-mobile.png",
    None, None,  # .lp-stack images: display:none at every breakpoint -> dropped
    "assets/client-kabobs.png", "assets/client-paddy.png", "assets/client-tumbuh-lab.png",
    "assets/client-manaaji.png", "assets/client-ganeca.png", "assets/client-charlene-clinic.png",
    "assets/testi-wheels-poster.jpg", "assets/testi-lyla-poster.jpg",
    "assets/cta-team.jpg", "assets/logo-mil-footer.png",
]
pat = re.compile(r"data:([\w/+.-]+);base64,([A-Za-z0-9+/=\s]+)")
idx = 0
url_for = {}

def rep(m):
    global idx
    name = NAMES[idx]; idx += 1
    if name is None:
        return "__DROPPED__"
    data = base64.b64decode(re.sub(r"\s", "", m.group(2)))
    open(f"{ROOT}/public/{name}", "wb").write(data)
    url_for[name] = "/" + name
    return "/" + name

body_and_head = pat.sub(rep, html)
assert idx == len(NAMES), idx

# Videos stored as Base64 text in <script type="text/plain">.
for vid in ("wheels", "lyla"):
    m = re.search(r'<script id="tv-data-%s" type="text/plain">([^<]+)</script>' % vid, body_and_head)
    open(f"{ROOT}/public/assets/testi-{vid}.mp4", "wb").write(base64.b64decode(m.group(1)))
    body_and_head = body_and_head.replace(m.group(0), "")

# Footer logo is byte-identical to the nav logo? Then reuse one file.
a = hashlib.sha1(open(f"{ROOT}/public/assets/logo-mil.png", "rb").read()).hexdigest()
b = hashlib.sha1(open(f"{ROOT}/public/assets/logo-mil-footer.png", "rb").read()).hexdigest()
if a == b:
    os.remove(f"{ROOT}/public/assets/logo-mil-footer.png")
    body_and_head = body_and_head.replace("/assets/logo-mil-footer.png", "/assets/logo-mil.png")
    print("footer logo == nav logo, deduplicated")

# Lossless WebP for the two heavy logo-wall PNGs (pixel-identical, much smaller).
for n in ("clients-desktop", "clients-mobile"):
    png, webp = f"{ROOT}/public/assets/{n}.png", f"{ROOT}/public/assets/{n}.webp"
    subprocess.run(["cwebp", "-quiet", "-lossless", "-z", "9", png, "-o", webp], check=True)
    if os.path.getsize(webp) < os.path.getsize(png):
        os.remove(png)
        body_and_head = body_and_head.replace(f"/assets/{n}.png", f"/assets/{n}.webp")
        print(n, "-> lossless webp", os.path.getsize(webp))
    else:
        os.remove(webp)

# ---------- CSS ----------
head = body_and_head.split("</head>")[0]
styles = re.findall(r"<style(?: id=\"([\w-]+)\")?>(.*?)</style>", head, re.S)
fw_style = re.search(r'<section class="sec fw" id="framework">\s*<style>(.*?)</style>', body_and_head, re.S).group(1)
font_faces = "\n".join(re.findall(r"@font-face\{[^}]+\}", styles[0][1]))

def ts_str(s):
    return json.dumps(s, ensure_ascii=False)

with open(f"{ROOT}/src/site/generated/styles.ts", "w") as f:
    f.write("// AUTO-GENERATED by scripts/extract_original.py — do not edit by hand.\n")
    f.write("// Verbatim copies of every <style> block of the original landing page.\n\n")
    f.write("export const HEAD_STYLES: { id: string | null; css: string }[] = [\n")
    for sid, css in styles:
        f.write(f"  {{ id: {ts_str(sid) if sid else 'null'}, css: {ts_str(css)} }},\n")
    f.write("];\n\n")
    f.write(f"export const FRAMEWORK_STYLE = {ts_str(fw_style)};\n")

# ---------- Icons ----------
body = body_and_head.split("<body>")[1].split("</body>")[0]
svgs = {}
def svg_after(marker, n=0):
    i = body.index(marker)
    for _ in range(n + 1):
        i = body.index("<svg", i + 1) if _ else body.index("<svg", i)
        if _ < n: i += 1
    j = body.index("</svg>", i) + 6
    return body[i:j]

# Collect every svg in order with a nearby text label to build named icons.
all_svgs = [(m.start(), m.group(0)) for m in re.finditer(r"<svg.*?</svg>", body, re.S)]
def label_after(pos_end):
    m = re.match(r"\s*(?:<i class=\"b\">\d</i></span><span class=\"t\">)?([^<]*)", body[pos_end:])
    return m.group(1).strip() if m else ""

TAG_KEYS = {
    "Research": "research", "Go-to-Market Strategy": "go-to-market", "Competitive Analysis": "competitive",
    "Meta": "meta", "TikTok": "tiktok", "Shopee": "shopee", "Google": "google",
    "Social Media Management": "social-media", "Advertising Creative Production": "ad-creative",
    "Brand Identity Design": "brand-identity", "In-Depth Interview": "interview",
    "Focus Group Discussion": "focus-group", "Customer Survey": "survey",
    "Website Development": "web-dev", "Keyword Research": "keyword", "Content Optimization": "content-opt",
}
TAG_LABELS = {v: k for k, v in TAG_KEYS.items()}
icons = {"tag": {}, "card": {}, "workflow": [], "misc": {}}
for pos, svg in all_svgs:
    end = pos + len(svg)
    before = body[max(0, pos - 40):pos]
    after = label_after(end)
    if before.endswith("<li>") and after in TAG_KEYS:
        icons["tag"][TAG_KEYS[after]] = {"label": after, "svg": svg}
    elif before.endswith('<div class="ico">'):
        title = re.search(r"<h3>(.*?)</h3>", body[end:end + 300]).group(1)
        key = {"Consulting": "consulting", "Advertising Strategy &amp; Optimization": "advertising",
               "Creative Solution": "creative"}[title]
        icons["card"][key] = {"label": title.replace("&amp;", "&"), "svg": svg}
    elif before.endswith('<div class="a-card">'):
        title = re.match(r"<b>(.*?)</b>", body[end:]).group(1)
        key = {"User Research": "user-research", "Website Development &amp; SEO": "website"}[title]
        icons["card"][key] = {"label": title.replace("&amp;", "&"), "svg": svg}
    elif before.endswith('<span class="n">'):
        icons["workflow"].append(svg)
    elif before.endswith('<div class="t-card">'):
        icons["misc"]["placeholder"] = svg
    elif "Chat WhatsApp" in before:
        icons["misc"]["whatsapp"] = svg
    elif "i-replay" in svg:
        icons["misc"]["replay"] = svg
    elif "i-play" in svg:
        icons["misc"]["play"] = svg
    elif "mwArrF" in svg or 'viewBox="0 0 400 400"' in svg:
        pass  # the workflow cycle diagram: kept verbatim in the template
    else:
        print("UNCLASSIFIED SVG:", before[-40:], svg[:80])

with open(f"{ROOT}/src/site/generated/icons.ts", "w") as f:
    f.write("// AUTO-GENERATED by scripts/extract_original.py — original inline SVGs, verbatim.\n\n")
    f.write(f"export const TAG_ICONS: Record<string, {{ label: string; svg: string }}> = {json.dumps(icons['tag'], ensure_ascii=False, indent=2)};\n\n")
    f.write(f"export const CARD_ICONS: Record<string, {{ label: string; svg: string }}> = {json.dumps(icons['card'], ensure_ascii=False, indent=2)};\n\n")
    f.write(f"export const WORKFLOW_ICONS: string[] = {json.dumps(icons['workflow'], ensure_ascii=False, indent=2)};\n\n")
    f.write(f"export const MISC_ICONS = {json.dumps(icons['misc'], ensure_ascii=False, indent=2)} as const;\n")
print("icons:", {k: len(v) for k, v in icons.items()})

# ---------- Intrinsic sizes ----------
dims = {}
for fn in sorted(os.listdir(f"{ROOT}/public/assets")):
    p = f"{ROOT}/public/assets/{fn}"
    if fn.endswith((".png", ".jpg", ".webp")):
        out = subprocess.run(["sips", "-g", "pixelWidth", "-g", "pixelHeight", p], capture_output=True, text=True).stdout
        w = int(re.search(r"pixelWidth: (\d+)", out).group(1)); h = int(re.search(r"pixelHeight: (\d+)", out).group(1))
        dims["/assets/" + fn] = {"width": w, "height": h, "size": os.path.getsize(p)}
    else:
        dims["/assets/" + fn] = {"size": os.path.getsize(p)}
with open(f"{ROOT}/src/site/generated/assets.ts", "w") as f:
    f.write("// AUTO-GENERATED by scripts/extract_original.py\n")
    f.write(f"export const BUNDLED_ASSETS: Record<string, {{ width?: number; height?: number; size: number }}> = {json.dumps(dims, indent=2)};\n")

# ---------- Normalised original body for the fidelity test ----------
open(f"{ROOT}/scripts/.original-body.html", "w").write(body)
for k, v in dims.items():
    print(k, v)

# ---------- Verbatim scripts + workflow cycle diagram ----------
fw_script = re.search(r'<section class="sec fw" id="framework">.*?<script>(.*?)</script>', body, re.S).group(1)
float_script = re.search(r'<script>(\(function\(\)\{var f=document\.querySelector\("\.wa-float"\).*?)</script>', body, re.S).group(1)
tv_script = re.search(r'<script id="tv-js">(.*?)</script>', body, re.S).group(1)
cycle_svg = re.search(r'(<svg viewBox="0 0 400 400".*?</svg>)', body, re.S).group(1)
with open(f"{ROOT}/src/site/generated/scripts.ts", "w") as f:
    f.write("// AUTO-GENERATED by scripts/extract_original.py — original inline scripts, verbatim.\n\n")
    f.write(f"export const FRAMEWORK_SCRIPT = {ts_str(fw_script)};\n\n")
    f.write(f"export const WA_FLOAT_SCRIPT = {ts_str(float_script)};\n\n")
    f.write(f"export const TESTIMONIAL_VIDEO_SCRIPT = {ts_str(tv_script)};\n\n")
    f.write(f"export const WORKFLOW_CYCLE_SVG = {ts_str(cycle_svg)};\n")
print("scripts extracted")
