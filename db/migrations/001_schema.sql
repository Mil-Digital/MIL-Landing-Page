create or replace function public.tg_page_content_touch()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  new.updated_at := now();
  if public.current_app_user() is not null then
    new.updated_by := public.current_app_user();
    if tg_op = 'INSERT' or new.draft_value is distinct from old.draft_value then
      update public.site_status
         set last_draft_saved_at = now(),
             last_draft_saved_by_email = (select email from public.admin_users where user_id = public.current_app_user())
       where id = 1;
    end if;
  end if;
  return new;
end $$;

drop trigger if exists page_content_touch on public.page_content;
create trigger page_content_touch before insert or update on public.page_content
  for each row execute function public.tg_page_content_touch();

create or replace function public.tg_touch_updated_at()
returns trigger language plpgsql as $$ begin new.updated_at := now(); return new; end $$;

drop trigger if exists media_assets_touch on public.media_assets;
create trigger media_assets_touch before update on public.media_assets
  for each row execute function public.tg_touch_updated_at();

