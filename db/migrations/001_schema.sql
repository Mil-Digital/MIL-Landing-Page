-- Public: published content as {section: {field: value}}. Never exposes drafts.
create or replace function public.get_published_content()
returns jsonb
language sql stable security definer
set search_path = public
as $$
  select coalesce(jsonb_object_agg(section_id, fields), '{}'::jsonb)
  from (
    select section_id, jsonb_object_agg(field_key, published_value) as fields
    from public.page_content
    where published_value is not null
    group by section_id
  ) t;
$$;

create or replace function public.publish_site(p_note text default null)
returns int
language plpgsql security definer
set search_path = public
as $$
declare
  v_version int;
  v_email   text;
  v_snap    jsonb;
begin
  if not public.is_admin() then
    raise exception 'Not authorized' using errcode = '42501';
  end if;

  update public.page_content
     set published_value = draft_value, published_at = now()
   where draft_value is distinct from published_value;

  select coalesce(jsonb_object_agg(section_id, fields), '{}'::jsonb) into v_snap
  from (
    select section_id, jsonb_object_agg(field_key, published_value) as fields
    from public.page_content where published_value is not null group by section_id
  ) t;

  select email into v_email from public.admin_users where user_id = public.current_app_user();
  perform pg_advisory_xact_lock(4242);
  select coalesce(max(version_number), 0) + 1 into v_version from public.content_versions;

  insert into public.content_versions (version_number, snapshot, note, published_by, published_by_email)
  values (v_version, v_snap, nullif(trim(p_note), ''), public.current_app_user(), v_email);

  update public.site_status
     set last_published_at = now(), last_published_by_email = v_email, published_version = v_version
   where id = 1;

  return v_version;
end $$;

create or replace function public.restore_version(p_version int)
returns int
language plpgsql security definer
set search_path = public
as $$
declare v_count int;
begin
  if not public.is_admin() then
    raise exception 'Not authorized' using errcode = '42501';
  end if;
  if not exists (select 1 from public.content_versions where version_number = p_version) then
    raise exception 'Version % not found', p_version;
  end if;
  update public.page_content pc
     set draft_value = f.value
    from public.content_versions cv,
         jsonb_each(cv.snapshot) as sec(key, value),
         jsonb_each(sec.value)   as f(key, value)
   where cv.version_number = p_version and pc.section_id = sec.key and pc.field_key = f.key;
  get diagnostics v_count = row_count;
  return v_count;
end $$;

create or replace function public.discard_draft()
returns int
language plpgsql security definer
set search_path = public
as $$
declare v_count int;
begin
  if not public.is_admin() then
    raise exception 'Not authorized' using errcode = '42501';
  end if;
  update public.page_content set draft_value = published_value
   where published_value is not null and draft_value is distinct from published_value;
  get diagnostics v_count = row_count;
  return v_count;
end $$;

