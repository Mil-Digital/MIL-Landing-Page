-- =====================================================================
--  MIL Digital CMS — schema for Neon Postgres
--  LANGKAH 2 — jalankan di Neon SQL Editor (sebagai neondb_owner),
--  setelah db/00_create_app_role.sql. Aman dijalankan ulang (idempotent).
--  Lalu jalankan db/seed.sql.
--
--  Security model
--  - The app connects as role `cms_app` (no BYPASSRLS, owns nothing).
--  - Every admin request runs in a transaction that sets `app.user_id`
--    (the Better Auth user id, verified server-side from the session).
--  - RLS policies on all CMS tables require public.is_admin().
--  - cms_app may only write DRAFT columns; published content changes only
--    through publish_site() (security definer).
--  - Visitors never touch tables: the public page calls get_published_content().
-- =====================================================================

do $$
begin
  if not exists (select 1 from pg_roles where rolname = 'cms_app') then
    raise exception 'Role cms_app belum ada. Jalankan db/00_create_app_role.sql terlebih dahulu.';
  end if;
end $$;

