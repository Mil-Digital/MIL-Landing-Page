-- 2. CMS tables
-- ---------------------------------------------------------------------
create table if not exists public.admin_users (
  user_id    text primary key references "user" ("id") on delete cascade,
  email      text not null,
  full_name  text,
  role       text not null default 'editor' check (role in ('owner', 'editor')),
  created_at timestamptz not null default now()
);

create table if not exists public.page_sections (
  id          text primary key,
  label       text not null,
  description text,
  sort_order  int  not null default 0,
  created_at  timestamptz not null default now()
);

create table if not exists public.page_content (
  section_id      text not null references public.page_sections (id) on delete cascade,
  field_key       text not null,
  field_type      text not null check (field_type in
                    ('text','textarea','inline','url','number','image','video','icon','select','list','repeater')),
  draft_value     jsonb,
  published_value jsonb,
  updated_at      timestamptz not null default now(),
  updated_by      text references "user" ("id") on delete set null,
  published_at    timestamptz,
  primary key (section_id, field_key)
);

create table if not exists public.media_assets (
  id               uuid primary key default gen_random_uuid(),
  bucket           text not null,
  storage_path     text not null unique,
  public_url       text not null,
  file_name        text not null,
  mime_type        text not null,
  kind             text not null check (kind in ('image', 'video', 'other')),
  size_bytes       bigint not null default 0,
  width            int,
  height           int,
  duration_seconds numeric,
  alt_text         text,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now(),
  uploaded_by      text references "user" ("id") on delete set null
);
create index if not exists media_assets_created_idx on public.media_assets (created_at desc);

create table if not exists public.content_versions (
  id                 bigint generated always as identity primary key,
  version_number     int not null unique,
  snapshot           jsonb not null,
  note               text,
  published_at       timestamptz not null default now(),
  published_by       text references "user" ("id") on delete set null,
  published_by_email text
);

create table if not exists public.site_status (
  id                        smallint primary key default 1 check (id = 1),
  last_draft_saved_at       timestamptz,
  last_draft_saved_by_email text,
  last_published_at         timestamptz,
  last_published_by_email   text,
  published_version         int
);
insert into public.site_status (id) values (1) on conflict do nothing;

-- ---------------------------------------------------------------------
-- 3. Identity helpers
-- ---------------------------------------------------------------------
create or replace function public.current_app_user()
returns text language sql stable
as $$ select nullif(current_setting('app.user_id', true), '') $$;

create or replace function public.is_admin()
returns boolean
language sql stable security definer
set search_path = public
as $$
  select exists (select 1 from public.admin_users where user_id = public.current_app_user());
$$;

